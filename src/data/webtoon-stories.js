  /**
   * Format dynamic receipt values based on calculator result (`calcRes`) and `preset`
   */
  function resolveDynamicReceiptValues(preset, calcRes) {
    const calcKey = preset.calc || preset.calcKey || 'electric';
    const inp = preset.inputs || {};
    const slugKey = preset.id || preset.slug || 'electric-studio-ac';
    const custom = PRESET_WEBTOON_MAP[slugKey] || PRESET_WEBTOON_MAP['electric-studio-ac'];
    const shortCartoon = SHORT_4CUT_BY_SLUG[slugKey] || SHORT_4CUT_BY_SLUG['electric-studio-ac'];
    const baseMeta = CATEGORY_META[calcKey] || CATEGORY_META.electric;

    let badVal = '';
    let goodVal = '';
    let diffVal = '';

    if (calcKey === 'electric') {
      badVal = calcRes && calcRes.afterBill ? `${calcRes.afterBill.toLocaleString()}원/월` : '88,420원/월';
      goodVal =
        calcRes && calcRes.afterBill && calcRes.monthlySaving
          ? `${Math.max(0, calcRes.afterBill - calcRes.monthlySaving).toLocaleString()}원/월`
          : '31,200원/월';
      diffVal = calcRes && calcRes.monthlySaving ? `-${calcRes.monthlySaving.toLocaleString()}원/월 절약` : '-57,220원/월 절약';
    } else if (calcKey === 'diet') {
      const weeks = (calcRes && calcRes.weeks) || inp.weeks || 4;
      const packs = (calcRes && calcRes.chickenPacks) || 100;
      const bowls = (calcRes && calcRes.brownRiceBowls) || 56;
      const retailCost = packs * 2900 + bowls * 2200;
      const bulkCost = packs * 1250 + bowls * 1050;
      const saved = Math.max(0, retailCost - bulkCost);
      badVal = `${retailCost.toLocaleString()}원/${weeks}주`;
      goodVal = `${bulkCost.toLocaleString()}원 (${packs}팩)`;
      diffVal = `-${saved.toLocaleString()}원 절약`;
    } else if (calcKey === 'pet') {
      const dailyG = (calcRes && calcRes.dailyGrams) || 85;
      const halfG = (calcRes && calcRes.halfGrams) || Math.round(dailyG / 2);
      const bagKg = (calcRes && calcRes.bagKg) || inp.bagKg || 2.0;
      const days = (calcRes && calcRes.daysPerBag) || 22;
      badVal = `일 ${Math.round(dailyG * 1.35)}g 과급여 (질환 위험)`;
      goodVal = `일 ${dailyG}g (${bagKg}kg=${days}일)`;
      diffVal = `1끼 ${halfG}g 정량 · 의료비 방어`;
    } else if (calcKey === 'room') {
      const total = (calcRes && calcRes.totalCost) || (inp.budgetMan || 100) * 10000;
      const saving = (calcRes && calcRes.savingWon) || Math.round(total * 0.28);
      badVal = `${(total + saving).toLocaleString()}원`;
      goodVal = `${total.toLocaleString()}원`;
      diffVal = `-${saving.toLocaleString()}원 절약`;
    } else if (calcKey === 'auto') {
      const inst = (calcRes && calcRes.installmentTco) || 54820000;
      const rent = (calcRes && calcRes.rentTco) || 46150000;
      const diffMan = (calcRes && calcRes.diffMan) || Math.round(Math.abs(inst - rent) / 10000);
      badVal = `${inst.toLocaleString()}원`;
      goodVal = `${rent.toLocaleString()}원`;
      diffVal = `-${diffMan.toLocaleString()}만 원 차이`;
    } else if (calcKey === 'telecom') {
      const netTotal = (calcRes && calcRes.totalNetBenefit) || 518000;
      const immNet = (calcRes && calcRes.immediateNetWon) || 320000;
      badVal = '0원 (기존 요금 그대로 납부)';
      goodVal = `+${netTotal.toLocaleString()}원 순이익`;
      diffVal = `당일 현금 +${immNet.toLocaleString()}원`;
    }

    return {
      species: baseMeta.species,
      accent: baseMeta.accent,
      charName: baseMeta.charName,
      expertName: baseMeta.expertName,
      sfxShock: baseMeta.sfxShock,
      badge: custom.badge,
      panel1Speech: custom.panel1Speech,
      panel1Sub: custom.panel1Sub,
      panel2Speech: custom.panel2Speech,
      panel2Sub: custom.panel2Sub,
      receiptTitle: custom.receiptTitle,
      badLabel: custom.badLabel,
      badVal,
      goodLabel: custom.goodLabel,
      goodVal,
      diffLabel: custom.diffLabel,
      diffVal,
      ctaTitle: custom.ctaTitle,
      hookLine: custom.hookLine,
      factLine: custom.factLine,
      closingLine: custom.closingLine,
      hashtags: custom.hashtags,
      shortCartoon
    };
  }

